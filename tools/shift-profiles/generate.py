"""Generate the compiled profile table; development only, never needed by users.

The input contains only vehicle IDs and native scalar RPM parameters. Do not
include extracted game assets, keys, installation paths or player information.
"""
from pathlib import Path
import json
import re

root = Path(__file__).resolve().parents[2]
source = Path(__file__).with_name('acc-1.10.4.json')
target = root / 'src/ACCDualSenseFeedback/Haptics/AccShiftProfiles.g.cs'
data = json.loads(source.read_text(encoding='utf-8'))
profiles = sorted(data['profiles'], key=lambda p: p['carModel'])
assert re.fullmatch(r'\d+\.\d+\.\d+', data['gameVersion'])
assert len({p['carModel'] for p in profiles}) == len(profiles)
for p in profiles:
    assert re.fullmatch(r'[a-z0-9_]+', p['carModel'])
    assert all(type(p[k]) is int for k in ('suggestedRpm', 'alarmRpm', 'limiterRpm'))
    assert 1000 < p['suggestedRpm'] <= p['alarmRpm'] < p['limiterRpm'] <= 16000

lines = [
    '// <auto-generated/>',
    '// Generated by tools/shift-profiles/generate.py from native ACC parameters.',
    '// The shipping app does not read game files or require this generator.',
    'namespace ACCDualSenseFeedback.Haptics;',
    '',
    'internal readonly record struct AccShiftProfile(',
    '    string CarModel, int SuggestedRpm, int AlarmRpm, int LimiterRpm);',
    '',
    'internal static class AccShiftProfiles',
    '{',
    f'    internal const string SourceVersion = "{data["gameVersion"]}";',
    '    private static readonly AccShiftProfile[] Profiles =',
    '    [',
]
for p in profiles:
    lines.append(f'        new("{p["carModel"]}", {p["suggestedRpm"]}, {p["alarmRpm"]}, {p["limiterRpm"]}),')
lines += [
    '    ];',
    '',
    '    internal static ReadOnlySpan<AccShiftProfile> All => Profiles;',
    '',
    '    // Called only when the telemetry car ID changes; no per-frame search.',
    '    internal static bool TryGet(string carModel, out AccShiftProfile profile)',
    '    {',
    '        foreach (var candidate in Profiles)',
    '            if (string.Equals(candidate.CarModel, carModel, StringComparison.Ordinal))',
    '            { profile = candidate; return true; }',
    '        profile = default;',
    '        return false;',
    '    }',
    '}',
    '',
]
target.write_text('\n'.join(lines), encoding='utf-8')
print(f'Generated {len(profiles)} profiles ({target.stat().st_size} source bytes).')
